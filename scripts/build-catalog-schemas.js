#!/usr/bin/env node
/*
 * Generates js/catalog-schemas.data.js from data/category_field_schemas.json.
 *
 * data/ is the canonical source (the server seeds category_field_schemas
 * from it and serve.py never exposes it); the generated script ships the
 * same document to the intake console so the form works offline and before
 * GET /api/catalog/field-schemas answers. tests/catalog-schemas-data.test.js
 * fails if the two drift — rerun `npm run build:schemas` after editing.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "data", "category_field_schemas.json");
const target = path.join(root, "js", "catalog-schemas.data.js");

function render(doc) {
  return [
    "/* GENERATED by scripts/build-catalog-schemas.js from data/category_field_schemas.json.",
    "   Do not edit by hand — run `npm run build:schemas`. */",
    `window.ADONAI_CATEGORY_FIELD_SCHEMAS = ${JSON.stringify(doc)};`,
    ""
  ].join("\n");
}

function build({ check = false } = {}) {
  const doc = JSON.parse(fs.readFileSync(source, "utf8"));
  const output = render(doc);
  if (check) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== output) {
      console.error("js/catalog-schemas.data.js is stale. Run: npm run build:schemas");
      process.exitCode = 1;
    }
    return output;
  }
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(root, target)} (${Object.keys(doc.schemas || {}).length} schemas, v${doc.version})`);
  return output;
}

if (require.main === module) build({ check: process.argv.includes("--check") });
module.exports = { build, render, source, target };
